"""Render lyrics documents as Roblox Lua tables.

Two shapes come out of here:

* `entry()` - one song, keyed by its id, ready to paste into an existing table::

        ["100847230469970"] = {
            SoundId = 100847230469970,
            Unsynced = false,
            Lyrics = {
                {Line = "first line", TimeStart = 0.695, TimeEnd = 6.114, Id = "L1"},
            }
        },

* `library()` - every song wrapped in `return { ... }` as a ModuleScript.

`RightAligned` is only written when it is true and `Adlibs` is left out entirely,
since the Lua format keeps entries on one line.
"""

from __future__ import annotations

import re
from typing import Any, Iterable

TAB = "\t"

_ESCAPES = {
    "\\": "\\\\",
    '"': '\\"',
    "\n": "\\n",
    "\r": "\\r",
    "\t": "\\t",
    "\a": "\\a",
    "\b": "\\b",
    "\f": "\\f",
    "\v": "\\v",
}


def quote(text: str) -> str:
    """Lua double-quoted string. UTF-8 passes through; Roblox reads it fine."""
    out = []
    for char in text:
        if char in _ESCAPES:
            out.append(_ESCAPES[char])
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            out.append(f"\\{ord(char):03d}")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def number(value: float) -> str:
    """Keep the exact value - the certification end time is deliberately unrounded."""
    if isinstance(value, int):
        return str(value)
    return repr(float(value))


def entry(document: dict[str, Any], *, base_indent: int = 1, indent: str = TAB) -> str:
    """One `["id"] = { ... },` block."""
    pad = indent * base_indent
    inner = indent * (base_indent + 1)
    line_pad = indent * (base_indent + 2)

    sound_id = int(document["SoundId"])
    rows = [
        f'{pad}[{quote(str(sound_id))}] = {{',
        f"{inner}SoundId = {sound_id},",
        f"{inner}Unsynced = {'true' if document.get('Unsynced') else 'false'},",
        f"{inner}Lyrics = {{",
    ]

    for item in document["Lyrics"]:
        fields = [
            f"Line = {quote(item['Line'])}",
            f"TimeStart = {number(item['TimeStart'])}",
            f"TimeEnd = {number(item['TimeEnd'])}",
            f"Id = {quote(item['Id'])}",
        ]
        if item.get("RightAligned"):
            fields.insert(1, "RightAligned = true")
        rows.append(f"{line_pad}{{{', '.join(fields)}}},")

    rows.append(f"{inner}}}")
    rows.append(f"{pad}}},")
    return "\n".join(rows)


def library(documents: Iterable[dict[str, Any]], *, header: str | None = None) -> str:
    """A complete ModuleScript returning every song, keyed by sound id."""
    banner = header if header is not None else (
        "-- Generated by lyricsync. Re-running lyricsync rewrites this file.\n"
        "-- Usage:  local Lyrics = require(script.LyricsLibrary)\n"
        "--         local song = Lyrics[tostring(sound.SoundId)]\n"
    )
    body = "\n".join(entry(document, base_indent=1) for document in documents)
    if not body:
        return f"{banner}\nreturn {{}}\n"
    return f"{banner}\nreturn {{\n{body}\n}}\n"


# --------------------------------------------------------------------- parsing

_UNESCAPE = {"\\": "\\", '"': '"', "'": "'", "n": "\n", "r": "\r", "t": "\t",
             "a": "\a", "b": "\b", "f": "\f", "v": "\v"}

_LINE_FIELD = r'{key}\s*=\s*"((?:[^"\\]|\\.)*)"'
_NUM_FIELD = r"{key}\s*=\s*(-?\d*\.?\d+(?:[eE][-+]?\d+)?)"


def _match_brace(text: str, open_at: int) -> int:
    """Index of the `}` closing the `{` at open_at, ignoring braces inside strings."""
    depth = 0
    in_string = False
    escape = False
    for i in range(open_at, len(text)):
        char = text[i]
        if in_string:
            if escape:
                escape = False
            elif char == "\\":
                escape = True
            elif char == '"':
                in_string = False
            continue
        if char == '"':
            in_string = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return i
    raise ValueError("unbalanced braces in the Lua table")


def _blocks(text: str) -> list[str]:
    """The contents of every top-level {...} in text."""
    found: list[str] = []
    i = 0
    in_string = False
    escape = False
    while i < len(text):
        char = text[i]
        if in_string:
            if escape:
                escape = False
            elif char == "\\":
                escape = True
            elif char == '"':
                in_string = False
        elif char == '"':
            in_string = True
        elif char == "{":
            end = _match_brace(text, i)
            found.append(text[i + 1:end])
            i = end
        i += 1
    return found


def _strip_comments(text: str) -> str:
    """Drop `--` line comments that are not inside a string."""
    out: list[str] = []
    i = 0
    in_string = False
    escape = False
    while i < len(text):
        char = text[i]
        if in_string:
            out.append(char)
            if escape:
                escape = False
            elif char == "\\":
                escape = True
            elif char == '"':
                in_string = False
        elif char == '"':
            in_string = True
            out.append(char)
        elif char == "-" and text[i:i + 2] == "--":
            newline = text.find("\n", i)
            if newline == -1:
                break
            i = newline
            continue
        else:
            out.append(char)
        i += 1
    return "".join(out)


def unquote(body: str) -> str:
    """Turn the inside of a Lua string literal back into text."""
    out: list[str] = []
    i = 0
    while i < len(body):
        char = body[i]
        if char == "\\" and i + 1 < len(body):
            nxt = body[i + 1]
            if nxt in _UNESCAPE:
                out.append(_UNESCAPE[nxt])
                i += 2
                continue
            if nxt.isdigit():
                digits = ""
                j = i + 1
                while j < len(body) and body[j].isdigit() and len(digits) < 3:
                    digits += body[j]
                    j += 1
                out.append(chr(int(digits)))
                i = j
                continue
            out.append(nxt)
            i += 2
            continue
        out.append(char)
        i += 1
    return "".join(out)


def parse(text: str) -> list[dict[str, Any]]:
    """Read one or more songs out of a Lua table (a single entry or a whole library)."""
    text = _strip_comments(text)
    documents: list[dict[str, Any]] = []

    for match in re.finditer(r'\[\s*"?(\d+)"?\s*\]\s*=\s*\{', text):
        open_at = match.end() - 1
        document = _parse_song(text[open_at + 1:_match_brace(text, open_at)])
        if document:
            if not document["SoundId"]:
                document["SoundId"] = int(match.group(1))
            documents.append(document)

    if not documents and "SoundId" in text:
        open_at = text.index("{")
        document = _parse_song(text[open_at + 1:_match_brace(text, open_at)])
        if document:
            documents.append(document)

    if not documents:
        raise ValueError("no songs found - expected a Lua table with SoundId and Lyrics")
    return documents


def _parse_song(block: str) -> dict[str, Any] | None:
    sound = re.search(_NUM_FIELD.format(key="SoundId"), block)
    unsynced = re.search(r"Unsynced\s*=\s*(true|false)", block)
    lyrics = re.search(r"Lyrics\s*=\s*\{", block)

    entries: list[dict[str, Any]] = []
    if lyrics:
        open_at = lyrics.end() - 1
        for row in _blocks(block[open_at + 1:_match_brace(block, open_at)]):
            entry = _parse_row(row)
            if entry:
                entries.append(entry)
    if not entries:
        return None

    number = 0
    for entry in entries:
        if not entry["Id"]:
            number += 1
            entry["Id"] = f"L{number}"
        elif entry["Id"].startswith("L") and entry["Id"][1:].isdigit():
            number = int(entry["Id"][1:])

    return {
        "SoundId": int(float(sound.group(1))) if sound else 0,
        "Lyrics": entries,
        "Unsynced": bool(unsynced and unsynced.group(1) == "true"),
    }


def _parse_row(row: str) -> dict[str, Any] | None:
    start = re.search(_NUM_FIELD.format(key="TimeStart"), row)
    end = re.search(_NUM_FIELD.format(key="TimeEnd"), row)
    if not (start and end):
        return None
    line = re.search(_LINE_FIELD.format(key="Line"), row, re.S)
    ident = re.search(_LINE_FIELD.format(key="Id"), row, re.S)
    right = re.search(r"RightAligned\s*=\s*(true|false)", row)
    return {
        "RightAligned": bool(right and right.group(1) == "true"),
        "Line": unquote(line.group(1)) if line else "",
        "Id": unquote(ident.group(1)) if ident else "",
        "TimeStart": float(start.group(1)),
        "TimeEnd": float(end.group(1)),
        "Adlibs": [],
    }
